export function resolveLocale(locale: Locale): ResolvedLocale {
  if (locale === "zh-CN") return "zh-CN"
  if (locale === "en") return "en"
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en"
}

export function useI18n(locale: Locale) {
  const resolved = useMemo(() => resolveLocale(locale), [locale])
  useEffect(() => {
    document.documentElement.lang = resolved === "zh-CN" ? "zh-CN" : "en"
  }, [resolved])
  const t = useMemo<Translate>(() => (key, values = {}) => {
    const template = messages[resolved][key] ?? messages.en[key] ?? key
    return Object.entries(values).reduce((result, [name, value]) => result.split(`{${name}}`).join(String(value)), template)
  }, [resolved])
  return { locale: resolved, t }
}
